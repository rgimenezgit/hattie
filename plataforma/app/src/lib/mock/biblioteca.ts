export type TipoArquivo = "foto" | "ilustracao" | "grafismo" | "peca" | "apresentacao" | "video" | "logo" | "documento"
export type OrigemArquivo = "hattie" | "voce" | "parceiro"
export type StatusArquivo = "rascunho" | "aprovado" | "publicado"
export type GrupoAparece = "produto" | "pessoa" | "personagem"

/** Como desenhar a miniatura enquanto não há arquivo de verdade. Cores são da marca da cliente. */
export type PreviaArquivo =
  | { tipo: "foto"; fundo: string; tinta: string; borda?: "top" | "bottom" | "left" | "right" }
  | { tipo: "ilustracao"; desenho: DesenhoIlustracao }
  | { tipo: "personagem"; pose: "frente" | "colhendo" }
  | { tipo: "grafismo"; desenho: "folhas" | "carimbo" | "padrao" }
  | { tipo: "peca"; exemplo: ExemploPeca; proporcao: [number, number] }
  | { tipo: "logo"; versao: "composta" | "simbolo"; fundo: string; tinta: string }
  | { tipo: "apresentacao"; capa: "foto" | "ilustracao"; titulo: string }
  | { tipo: "video"; fundo: string; tinta: string; duracao: string }
  | { tipo: "documento"; titulo: string }
  | { tipo: "enviada"; url: string }

export type ArquivoBiblioteca = {
  id: string
  nome: string
  tipo: TipoArquivo
  /** Frase que descreve o que se vê. É o que a busca por frase lê. */
  descricao: string
  formato: string
  extensao: "JPG" | "PNG" | "SVG" | "PDF" | "MP4" | "PPTX" | "DOCX"
  tamanho: string
  /** Data em ISO (AAAA-MM-DD). */
  data: string
  origem: OrigemArquivo
  parceiro?: string
  /** id de PROJETOS. */
  projeto?: string
  /** ids de QUEM_APARECE. */
  aparece: string[]
  tags: string[]
  /** Cores que mais aparecem (hex da marca). */
  cores: string[]
  status: StatusArquivo
  favorito?: boolean
  versao?: number
  /** ids de outros arquivos que usam este. */
  usadoEm?: string[]
  previa: PreviaArquivo
}

